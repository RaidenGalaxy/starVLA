 n6.exp<=final_exponent; n6.mant<=final_mantissa; n6.sbits<=sum_sticky_bits;
 n6.sign<=norm_sign8; n6.sub<=m8.sub; n6.sticky<=sticky_after_norm;
 n6.special<=m8.special; n6.sresult<=m8.sresult; n6.status<=m8.status;
