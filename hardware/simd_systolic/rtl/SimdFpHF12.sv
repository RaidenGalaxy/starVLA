  logic any_operand_nan;
  logic signalling_nan;
  logic effective_subtraction;
  logic tentative_sign;

  // Reduction for special case handling
  assign any_operand_inf = (| {s1_info_a.is_inf,        s1_info_b.is_inf,        s1_info_c.is_inf});
  assign any_operand_nan = (| {s1_info_a.is_nan,        s1_info_b.is_nan,        s1_info_c.is_nan});
  assign signalling_nan  = (| {s1_info_a.is_signalling, s1_info_b.is_signalling, s1_info_c.is_signalling});
