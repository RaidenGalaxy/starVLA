always_ff @(posedge clock) if(ce) begin
 rounded_abs10<=rounded_abs;rounded_sign10<=rounded_sign;
 pre_round10<=pre_round_abs;of_before10<=of_before_round;
 round_sticky10<=round_sticky_bits;norm10<=n6;
end
  // Classification after rounding
  assign uf_after_round = (rounded_abs10[EXP_BITS+MAN_BITS-1:MAN_BITS] == '0) // denormal
        || ((pre_round10[EXP_BITS+MAN_BITS-1:MAN_BITS] == '0) && (rounded_abs10[EXP_BITS+MAN_BITS-1:MAN_BITS] == 1) &&
           ((round_sticky10 != 2'b11) || (!norm10.sbits[MAN_BITS*2 + 4] && ((fpnew_pkg::RNE == fpnew_pkg::RNE) || (fpnew_pkg::RNE == fpnew_pkg::RMM)))));
  assign of_after_round = rounded_abs10[EXP_BITS+MAN_BITS-1:MAN_BITS] == '1; // exponent all ones

  // -----------------
  // Result selection
  // -----------------
  logic [WIDTH-1:0]     regular_result;
  fpnew_pkg::status_t   regular_status;

  // Assemble regular result
  assign regular_result    = {rounded_sign10, rounded_abs10};
  assign regular_status.NV = 1'b0; // only valid cases are handled in regular path
  assign regular_status.DZ = 1'b0; // no divisions
  assign regular_status.OF = of_before10 | of_after_round;   // rounding can introduce overflow
  assign regular_status.UF = uf_after_round & regular_status.NX; // only inexact results raise UF
  assign regular_status.NX = (| round_sticky10) | of_before10 | of_after_round;

  // Final results for output pipeline
  fp_t                result_d;
  fpnew_pkg::status_t status_d;

  // Select output depending on special case detection
  assign result_d = norm10.special ? norm10.sresult : regular_result;
  assign status_d = norm10.special ? norm10.status : regular_status;

  // ----------------

