  // Classification after rounding
  assign uf_after_round = (rounded_abs10[EXP_BITS+MAN_BITS-1:MAN_BITS] == '0) // denormal
        || ((pre_round10[EXP_BITS+MAN_BITS-1:MAN_BITS] == '0) && (rounded_abs10[EXP_BITS+MAN_BITS-1:MAN_BITS] == 1) &&
           ((round_sticky10 != 2'b11) || (!norm10.sbits[MAN_BITS*2 + 4] && ((fpnew_pkg::RNE == fpnew_pkg::RNE) || (fpnew_pkg::RNE == fpnew_pkg::RMM)))));
  assign of_after_round = rounded_abs10[EXP_BITS+MAN_BITS-1:MAN_BITS] == '1; // exponent all ones

  // -----------------
  // Result selection
  // -----------------
  logic [WIDTH-1:0]     regular_result;
  fpnew_pkg::status_t   regular_status;

  // Assemble regular result
  assign regular_result    = {rounded_sign10, rounded_abs10};
