 m3<=m2;coarse_c3<=shifted_c2;m4<=m3;
 m4.aligned<=shifted_c3[4*PRECISION_BITS+3:PRECISION_BITS];
 m4.csticky<=|shifted_c3[PRECISION_BITS-1:0];
end
logic [2*PRECISION_BITS-1:0] product;
SimdProductFast53 mult(.clock(clock),.ce(ce),
 .a({s1_info_a.is_normal,s1_operand_a.mantissa}),
 .b({s1_info_b.is_normal,s1_operand_b.mantissa}),.product(product));
logic [3*PRECISION_BITS+3:0] product_shifted,addend_after_shift,addend_shifted;
logic [PRECISION_BITS-1:0] addend_sticky_bits;
logic sticky_before_add,inject_carry_in;
assign product_shifted=product<<2;
assign addend_after_shift=m4.aligned;
assign addend_sticky_bits='0;
assign sticky_before_add=m4.csticky;
logic [3*PRECISION_BITS+3:0] prepared_addend4;
logic prepared_carry4;
always_ff @(posedge clock) if(ce) begin
 prepared_addend4<=m3.sub ? ~shifted_c3[4*PRECISION_BITS+3:PRECISION_BITS] : shifted_c3[4*PRECISION_BITS+3:PRECISION_BITS];
 prepared_carry4<=m3.sub & ~(|shifted_c3[PRECISION_BITS-1:0]);
end
assign addend_shifted=prepared_addend4;
assign inject_carry_in=prepared_carry4;
logic [3*PRECISION_BITS+4:0] sum_pos,sum_neg;
logic [3*PRECISION_BITS+3:0] sum;
logic sum_carry,final_sign;
SimdPrefixAdd #(.W(3*PRECISION_BITS+4)) positive_add(.a(product_shifted),.b(addend_shifted),.cin(inject_carry_in),.result(sum_pos));
logic [3*PRECISION_BITS+4:0] negative_full;
SimdPrefixAdd #(.W(3*PRECISION_BITS+4)) negative_add(.a(addend_after_shift),.b(~product_shifted),.cin(1'b1),.result(negative_full));
assign sum_neg={1'b0,negative_full[3*PRECISION_BITS+3:0]};
assign sum_carry=sum_pos[3*PRECISION_BITS+4];
assign sum=(m4.sub && !sum_carry) ? sum_neg : sum_pos;
assign final_sign=(m4.sub && (sum_carry==m4.sign)) ? 1'b1 : (m4.sub ? 1'b0 : m4.sign);
meta_t m5,m6;
logic [3*PRECISION_BITS+4:0] positive5,negative5;
logic sticky5;
