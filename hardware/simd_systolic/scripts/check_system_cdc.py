#!/usr/bin/env python3
"""Check actual system FIFO/reset/toggle connectivity, with explicit opaque leaves.

This inventories the crossings in elaborated controller RTL. Arithmetic,
single-clock controllers and SRAM bodies are boundaries, not CDC-certified by
this check. Gray-wire skew, bundled data timing and reset recovery/removal
still require a mapped physical implementation.
"""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path
from runtime import validated_build

ROOT=Path(__file__).resolve().parents[1]


def check(build_dir):
    dest=Path(build_dir).resolve();guard,caps=validated_build(dest)
    if caps['target']not in('system','gemm'):raise ValueError('a system or GEMM build is required')
    top='GemmSystem'if caps['target']=='gemm'else'TileSystem'
    out=ROOT/'.build'/('system_cdc_'+dest.name);out.mkdir(exist_ok=True)
    src=dest/'inputs';manifest=json.loads((dest/'rtl_manifest.json').read_text());stubs=[];boundaries=[]
    controllers=['TileSystem.sv']+(['GemmSystem.sv']if top=='GemmSystem'else[])
    for name in manifest:
        path=src/name;raw=path.read_text()
        if name in controllers or not raw.startswith('// Generated by CIRCT'):continue
        match=re.search(r'(?m)^module\s+(\w+)',raw)
        if not match:continue
        end=raw.index(');',match.start())+2
        stubs.append('(* blackbox *) '+raw[match.start():end]+'\nendmodule\n');boundaries.append(match[1])
    (out/'boundaries.sv').write_text('\n'.join(stubs))
    raw=(src/'SramBank.sv').read_text()
    sram_boundary=out/'sram_boundary.sv'
    sram_boundary.write_text('(* blackbox *) '+raw[raw.index('module '):raw.index(');')+2]+'\nendmodule\n')
    boundaries.append('SimdSramBank')
    commands=f'read_verilog -sv -lib {out/"boundaries.sv"}\nread_verilog -sv {src/"ControlReplicas.sv"}\n'
    commands+=f'read_slang --ignore-assertions --top {top} {sram_boundary} '+' '.join(str(src/n)for n in ['AsyncFifo.sv','PrefixAdd.sv']+controllers)+'\n'
    commands+=f'hierarchy -check -top {top}\nproc\nopt_clean\nwrite_json {out/"netlist.json"}\n'
    (out/'read.ys').write_text(commands)
    yosys=ROOT/'.deps/tools/oss-cad-suite/bin/yosys'
    if not yosys.exists():raise RuntimeError('Slang Yosys required; run scripts/bootstrap.py --physical')
    with(out/'read.log').open('w')as log:
        subprocess.run([str(yosys),'-Q','-T','-s',str(out/'read.ys')],stdout=log,stderr=subprocess.STDOUT,check=True)
    module=json.loads((out/'netlist.json').read_text())['modules'][top]
    nets,cells=module['netnames'],module['cells'];prefix='tile.'if top=='GemmSystem'else''
    core=nets['io_coreClock']['bits'];memory=nets['io_memoryClock']['bits']
    external_resets={tuple(nets['io_coreReset']['bits']),tuple(nets['io_memoryReset']['bits'])}
    def is_epoch_reset(bits):
        return any(cell['type'] in ('$or','$logic_or') and cell['connections'].get('Y')==bits and
            {tuple(cell['connections'].get('A',[])),tuple(cell['connections'].get('B',[]))}==external_resets
            for cell in cells.values())
    def singleton(kind,clock,external):
        found=[(name,cell)for name,cell in cells.items()if cell['type']==kind
            and cell['connections'].get('clock')==clock and is_epoch_reset(cell['connections'].get('externalReset'))]
        if kind=='SimdResetSynchronizer':
            expected=2 if top=='GemmSystem'and clock==memory else 1
            assert len(found)==expected,(kind,found)
        return found
    resets=singleton('SimdResetSynchronizer',core,nets['io_coreReset']['bits'])
    resets+=singleton('SimdResetSynchronizer',memory,nets['io_memoryReset']['bits'])
    reset_by_name={name:cell['connections']['value']for name,cell in resets}
    core_reset=reset_by_name[prefix+'coreReset_sync'];mem_reset=reset_by_name[prefix+'memoryReset_sync']
    def driver(bits):
        found=[(name,cell)for name,cell in cells.items()if cell['connections'].get('Q')==bits]
        assert len(found)==1,('ambiguous FF driver',bits)
        return found[0]
    def ff(name,clock,reset):
        bits=nets[name]['bits'];cellname,cell=driver(bits)
        assert cell['type']in('$adff','$aldff')and cell['connections']['CLK']==clock
        port='ARST'if cell['type']=='$adff'else'ALOAD'
        assert cell['connections'][port]==reset,(name,'reset domain')
        if cell['type']=='$aldff':assert set(cell['connections']['AD'])=={'0'}
        else:assert int(cell['parameters']['ARST_VALUE'],2)==0
        return cellname,cell
    def only_consumer(bits,expected_name,expected_port):
        bitset=set(bits)
        for name,cell in cells.items():
            for port,values in cell['connections'].items():
                if cell['port_directions'][port]=='input'and bitset&set(values):
                    assert(name,port)==(expected_name,expected_port),('synchronizer bypass',name,port)
    def toggle_local_feedback(bits,synchronizer):
        # The source toggles its own memory-domain register through XOR.
        # Permit that local feedback, but reject any other core-domain use.
        consumers={}
        for name,cell in cells.items():
            for port,values in cell['connections'].items():
                if cell['port_directions'][port]=='input':
                    for bit in values:
                        if isinstance(bit,int):consumers.setdefault(bit,[]).append((name,port))
        outputs={bit for port in module['ports'].values()if port['direction']=='output'for bit in port['bits']}
        todo=list(bits);seen=set()
        while todo:
            bit=todo.pop()
            if bit in seen:continue
            seen.add(bit);assert bit not in outputs,'raw toggle reaches an external output'
            for name,port in consumers.get(bit,[]):
                cell=cells[name]
                if(name,port)==(synchronizer,'data'):continue
                clocks=[value for pin,value in cell['connections'].items()if pin.lower()in('clk','clock')]
                if clocks:
                    assert all(clock==memory for clock in clocks),('toggle bypasses destination synchronizer',name)
                else:
                    todo.extend(b for pin,value in cell['connections'].items()if cell['port_directions'][pin]=='output'for b in value if isinstance(b,int))
    crossings=[]
    for fifo in ['waves','reads','results','dones','auxRequests','auxResults','seeds','seedAcks']:
        path=prefix+fifo+'.';reverse=fifo in('results','dones','auxResults','seedAcks')
        write_clock,read_clock=(core,memory)if reverse else(memory,core)
        write_reset,read_reset=(core_reset,mem_reset)if reverse else(mem_reset,core_reset)
        for source,first,second,sc,dc,reset in [
            ('wg','wg1','wg2',write_clock,read_clock,read_reset),
            ('rg','rg1','rg2',read_clock,write_clock,write_reset)]:
            source_bits=nets[path+source]['bits'];sn,source_cell=driver(source_bits)
            assert source_cell['connections']['CLK']==sc
            fn,fc=ff(path+first,dc,reset);tn,tc=ff(path+second,dc,reset)
            assert fc['connections']['D']==source_bits and tc['connections']['D']==nets[path+first]['bits']
            for stage in(first,second):assert nets[path+stage]['attributes'].get('ASYNC_REG')=='TRUE'
            only_consumer(source_bits,fn,'D');only_consumer(nets[path+first]['bits'],tn,'D')
            crossings.append(dict(fifo=fifo,source=path+source,first=path+first,second=path+second,
                width=len(source_bits),source_domain='core'if sc==core else'memory',
                destination_domain='core'if dc==core else'memory'))
    toggles=[(name,cell)for name,cell in cells.items()if cell['type']=='SimdToggleSynchronizer']
    assert len(toggles)==1
    toggle_name,toggle=toggles[0];assert toggle['connections']['clock']==core and toggle['connections']['reset']==core_reset
    _,source=driver(toggle['connections']['data']);assert source['connections']['CLK']==memory
    toggle_local_feedback(toggle['connections']['data'],toggle_name)
    report=dict(passed=True,scope='system_fifo_reset_toggle_connectivity',physical_signoff=False,
        target=caps['target'],stages=caps['stages'],rows=caps['rows'],cols=caps['cols'],
        gray_crossings=crossings,toggle_crossings=1,reset_synchronizers=len(resets),either_external_reset_flushes_both_fifo_endpoints=True,
        first_stages_do_not_drive_functional_logic=True,opaque_boundary_modules=sorted(boundaries),
        unchecked=['opaque block internals','other combinational crossing cones','physical Gray skew',
            'bundled FIFO data timing','metastability MTBF','reset recovery/removal'],
        rtl_sha256=caps['rtl_sha256'],netlist_sha256=hashlib.sha256((out/'netlist.json').read_bytes()).hexdigest())
    (out/'verification.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report))


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--build-dir',default=str(ROOT/'.build/gemm_2_2x2'))
    check(parser.parse_args().build_dir)
