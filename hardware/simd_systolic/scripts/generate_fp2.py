#!/usr/bin/env python3
"""Retain CVFPU arithmetic, with one internal cut and explicit wide carry trees."""
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def generate():
    raw=(ROOT/'vendor/fpnew_fma.sv').read_text()
    replacements={
        'module fpnew_fma #(':'module SimdFpF2Core #(',
        'fpnew_rounding #(':'SimdFpF2Rounding #(',
        'assign sum_pos = product_shifted + addend_shifted + inject_carry_in;':
        "SimdPrefixAdd #(.W(3*PRECISION_BITS+4)) positive_sum(.a(product_shifted), .b(addend_shifted), .cin(inject_carry_in), .result(sum_pos));",
        'assign sum_neg = addend_after_shift - product_shifted;':
        "logic [3*PRECISION_BITS+4:0] negative_full;\n  SimdPrefixAdd #(.W(3*PRECISION_BITS+4)) negative_sum(.a(addend_after_shift), .b(~product_shifted), .cin(1'b1), .result(negative_full));\n  assign sum_neg = {1'b0,negative_full[3*PRECISION_BITS+3:0]};"
    }
    for old,new in replacements.items():
        if raw.count(old)!=1:raise ValueError('upstream FMA changed: '+old)
        raw=raw.replace(old,new)
    rounding=(ROOT/'vendor/fpnew_rounding.sv').read_text().replace('module fpnew_rounding #(','module SimdFpF2Rounding #(')
    increment='assign abs_rounded_o = abs_value_i + round_up;'
    if rounding.count(increment)!=1:raise ValueError('upstream rounding changed')
    rounding=rounding.replace(increment,"logic [AbsWidth:0] rounded_full;\n  SimdPrefixAdd #(.W(AbsWidth)) increment(.a(abs_value_i),.b('0),.cin(round_up),.result(rounded_full));\n  assign abs_rounded_o = rounded_full[AbsWidth-1:0];")
    (ROOT/'rtl/SimdFpF2Core.sv').write_text('// Generated by scripts/generate_fp2.py; one internal F2 arithmetic cut.\n'+raw+'\n'+rounding)


if __name__=='__main__':generate()
